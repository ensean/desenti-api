from __future__ import annotations

import re

# ----------------------------------------------------------------------------
# 强格式正则实体。每条规则给出：实体类型、正则、基础置信度、校验函数（可选）
# ----------------------------------------------------------------------------

# 统一社会信用代码：18 位，由数字和大写字母（不含 I O S V Z）组成
CREDIT_CODE_RE = re.compile(r"[0-9A-HJ-NP-RT-UW-Y]{2}\d{6}[0-9A-HJ-NP-RT-UW-Y]{10}")

# 身份证号：18 位，前 17 位数字，末位数字或 X
ID_CARD_RE = re.compile(r"(?<!\d)\d{17}[\dXx](?!\d)")

# 手机号：1 开头 11 位；座机：区号-号码
MOBILE_RE = re.compile(r"(?<!\d)1[3-9]\d{9}(?!\d)")
LANDLINE_RE = re.compile(r"(?<!\d)0\d{2,3}[-\s]?\d{7,8}(?!\d)")

# 邮箱
EMAIL_RE = re.compile(r"[A-Za-z0-9._%+\-]+@[A-Za-z0-9.\-]+\.[A-Za-z]{2,}")

# 银行账号：12-19 位数字，允许中间空格分组（如 6225 8888 1234 5678）
BANK_ACCOUNT_RE = re.compile(r"(?<![\d])(?:\d[\d ]{10,24}\d)(?![\d])")

# 公司名称：以行政区/字号开头，以企业组织后缀结尾
COMPANY_SUFFIXES = (
    "有限公司", "股份有限公司", "有限责任公司", "集团有限公司", "集团",
    "事务所", "研究院", "研究所", "中心", "工作室", "合伙企业",
    "分公司", "办事处", "厂", "店", "银行", "合作社",
)
COMPANY_RE = re.compile(
    r"[\u4e00-\u9fa5（）()A-Za-z0-9]{2,40}?(?:"
    + "|".join(COMPANY_SUFFIXES)
    + r")"
)

# 银行/开户行名称：含“银行/信用社”等
BANK_NAME_RE = re.compile(
    r"[\u4e00-\u9fa5]{2,20}?(?:银行|信用社|信用合作联社|农村商业银行|村镇银行)"
    r"(?:[\u4e00-\u9fa5]{0,15}?(?:支行|分行|营业部|分理处|储蓄所))?"
)

# 中文人名：2-4 个汉字（用于关键词锚点后抽取）
PERSON_NAME_RE = re.compile(r"[\u4e00-\u9fa5]{2,4}")

# 地址：以行政区划层级关键字构成
ADDRESS_RE = re.compile(
    r"[\u4e00-\u9fa5]{2,}?(?:省|自治区|特别行政区)?"
    r"[\u4e00-\u9fa5]{0,}?(?:市|自治州)"
    r"[\u4e00-\u9fa5]{0,}?(?:区|县|市|旗)?"
    r"[\u4e00-\u9fa50-9（）()]{0,40}?(?:路|街|道|大道|巷|号|栋|幢|座|室|层|楼|号楼|大厦|广场|园|村|镇|乡)"
    r"[\u4e00-\u9fa50-9（）()\-]{0,20}"
)


